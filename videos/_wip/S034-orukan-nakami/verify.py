#!/usr/bin/env python3
"""S034「オルカンとS&P500を両方持つと、米国比率はいくつになるか」の数値検証。

欲求C(持っているものを無駄にしたくない)+ B(選択を間違えたくない)。
**自分のNISAの米国比率を計算して、意図と合っているか確かめられる。**

この動画は**個別銘柄を1つも推奨しない**(戦略§6-1)。
出てくるのは「全世界株のインデックス」と「米国株のインデックス」という
2つの**種類**であって、買うべき商品の話ではない。
組入銘柄名も出さない(推奨と読まれる余地を残さないため)。

| 前提 | 値 | 出どころ | 確度 |
|---|---|---|---|
| 全世界株インデックスの米国比率 | 約60% | 世界の株式時価総額に占める米国の割合 | B |
| 上位10銘柄の合計比率 | 約25%(4分の1) | 同ファンドの月次資料の要約が複数で一致 | B |
| 米国株インデックスの米国比率 | 100% | 定義そのもの | **A** |

**確度Bなのは、この環境から一次資料を開けないため。**
egress proxy が emaxis.am.mufg.jp を遮断する(2026-08-30確認)。
複数の解説記事が「米国が約6割」「上位10銘柄で約4分の1」で一致することを確認した。

**この比率は毎月動く。**株価が動けば時価総額の比率も動くので、
動画には必ず「2026年8月時点」の時点表記を入れる(戦略§6-5)。
だから台本では **「約6割」と幅で言い、小数第1位まで言わない。**

**投稿前にユーザーの環境で、運用会社の月次レポートを確認すること。**
"""

# ---- 2つのインデックスの米国比率(2026年8月時点。毎月動く)
WORLD_US = 0.60        # 全世界株インデックス
US_US = 1.00           # 米国株インデックス(定義上100%)

# 全世界株インデックスの中身(集中度)
TOP10_SHARE = 0.25     # 上位10銘柄の合計。約4分の1
HOLDINGS = 2_500       # 組入銘柄数(おおよそ)


def us_ratio(world_share: float) -> float:
    """全世界株を world_share の比率で持ち、残りを米国株で持ったときの米国比率。"""
    return world_share * WORLD_US + (1 - world_share) * US_US


# 「両方を半々で持っている」人の米国比率
HALF = us_ratio(0.5)

if __name__ == "__main__":
    print(f"全世界株インデックスの米国比率: 約{WORLD_US:.0%}(2026年8月時点)")
    print(f"  中身は約{HOLDINGS:,}銘柄。ただし上位10銘柄だけで約{TOP10_SHARE:.0%}")
    print(f"米国株インデックスの米国比率: {US_US:.0%}(定義上)")

    print("\n2つをどの割合で持つと、米国は何%になるか:")
    print(f"  {'全世界株':>8} : {'米国株':>6} | {'米国比率':>8}")
    for w in (1.0, 0.8, 0.7, 0.5, 0.3, 0.0):
        print(f"  {w:>7.0%} : {1-w:>6.0%} | {us_ratio(w):>7.0%}")

    print(f"\n**半々で持つと、米国は {HALF:.0%}**")
    assert abs(HALF - 0.80) < 1e-9, HALF

    # 「分散を増やしたつもりが、米国を増やしていた」の差
    print(f"\n全世界株だけ  → 米国 {WORLD_US:.0%}")
    print(f"半々で持つ    → 米国 {HALF:.0%}  (+{HALF - WORLD_US:.0%}ポイント)")
    assert abs((HALF - WORLD_US) - 0.20) < 1e-9

    # 100万円で言い換える(割合が苦手な人向け。台本で使う)
    MAN = 1_000_000
    print(f"\n100万円で言うと:")
    print(f"  全世界株だけ: 米国に {int(MAN * WORLD_US):,}円")
    print(f"  半々で持つ  : 米国に {int(MAN * HALF):,}円")
    assert int(MAN * WORLD_US) == 600_000
    assert int(MAN * HALF) == 800_000

    print("\n台本で言う値: 米国約6割 / 上位10銘柄で約4分の1 / "
          "半々なら米国8割 / 100万円なら60万円→80万円 ✓")
