#!/usr/bin/env python3
"""S020 の数値検証。動画内の数字はすべてここで再計算する。

問い: ふるさと納税の自己負担2000円は、寄付するたびに払うのか。
答え: 年に1回だけ。だから寄付先を分けるほど、2000円は薄まる。

前提(2026年8月時点・確認日 2026-08-18):
  自己負担2000円は**年間の合計**にかかる(自治体の数によらず一律)
  返礼品は寄付額の3割まで(総務省の3割基準)
  ただし控除の上限を超えた分は、税から引かれない
"""
JIKO = 2_000
RATE = 0.3


def main():
    ok = True

    def eq(name, got, want):
        nonlocal ok
        hit = got == want
        ok &= hit
        print(f"  [{'OK' if hit else 'NG'}] {name}: {got:,} (期待 {want:,})")

    print("S020 数値検証(自己負担2000円は年1回)")
    # 1自治体に1万円
    k1 = 10_000
    h1 = int(k1 * RATE)
    eq("1万円ぶんの返礼品", h1, 3_000)
    eq("1自治体だけのとき残る額", h1 - JIKO, 1_000)

    # 10自治体に1万円ずつ
    k10 = k1 * 10
    h10 = int(k10 * RATE)
    eq("10自治体ぶんの寄付", k10, 100_000)
    eq("10自治体ぶんの返礼品", h10, 30_000)
    eq("10自治体でも自己負担", JIKO, 2_000)
    eq("10自治体のとき残る額", h10 - JIKO, 28_000)

    # 分けるほど、寄付1万円あたりの自己負担は薄まる
    eq("1自治体のときの1万円あたり自己負担", JIKO // 1, 2_000)
    eq("10自治体のときの1万円あたり自己負担", JIKO // 10, 200)

    print("結果:", "全一致" if ok else "不一致あり")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
