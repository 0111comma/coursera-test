#!/usr/bin/env python3
"""S003: 新NISAの生涯投資枠1800万円を使い切るのにかかる年数の検証。

計算方法:
- 生涯の非課税保有限度額は1人1800万円(簿価=投資元本ベースで消費。運用益は枠を使わない)
- 年数 = 1800万円 ÷ 年間積立額(端数なしになる金額のみ動画で使用)
- 年間投資枠の上限: つみたて投資枠120万円(月10万円)+成長投資枠240万円=年360万円
  出典: 金融庁「NISA特設ウェブサイト」(確認日2026-08-12)
- 2026年度改正(枠の年内復活等)は2027年1月施行予定のため本動画の計算に影響しない
"""

LIMIT = 18_000_000

CASES = {          # 月額 → 年間
    5_000: 60_000,
    10_000: 120_000,
    30_000: 360_000,
    50_000: 600_000,
    100_000: 1_200_000,   # つみたて投資枠の上限(月10万円)
}
MAX_YEARLY = 3_600_000    # 両枠合計の年間上限

years = {m: LIMIT / y for m, y in CASES.items()}
assert all(v == int(v) for v in years.values()), years
assert [int(years[m]) for m in [5_000, 10_000, 30_000, 50_000, 100_000]] == [300, 150, 50, 30, 15]
assert LIMIT / MAX_YEARLY == 5.0

# 「江戸から令和」: 300年前が江戸時代(享保年間)であること
assert 2026 - 300 == 1726  # 江戸中期(享保11年)

for m, y in CASES.items():
    print(f"月{m:,}円(年{y:,}円) → {int(years[m])}年")
print(f"満額 年{MAX_YEARLY:,}円 → {int(LIMIT / MAX_YEARLY)}年(最短)")
print("OK: すべての数値が台本と一致")
