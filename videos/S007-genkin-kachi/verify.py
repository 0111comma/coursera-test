#!/usr/bin/env python3
"""S007: 物価上昇が続くと現金100万円の実質価値はいくらになるかの検証。

- 実質価値 = 100万円 ÷ (1+物価上昇率)^年数
- 物価率の例: 2%(日銀の物価安定の目標)/1.6%(2026年6月の全国CPI・生鮮食品を除く総合の前年比)
  出典: 日本銀行「物価安定の目標」/ 総務省統計局CPI(確認日2026-08-12)
"""

def real_value(rate: float, years: int, principal: float = 1_000_000) -> float:
    return principal / (1 + rate) ** years

v20_2 = real_value(0.02, 20)      # 672,971
v20_16 = real_value(0.016, 20)    # 728,000前後
v10_2 = real_value(0.02, 10)      # 820,348
v30_2 = real_value(0.02, 30)      # 552,071

assert round(v20_2 / 10_000) == 67, v20_2
assert round(v20_16 / 10_000) == 73, v20_16
assert round(v10_2 / 10_000) == 82, v10_2
assert round(v30_2 / 10_000) == 55, v30_2

print(f"物価2%: 10年後 {v10_2:,.0f}円(約82万) / 20年後 {v20_2:,.0f}円(約67万) / 30年後 {v30_2:,.0f}円(約55万)")
print(f"物価1.6%(直近CPI): 20年後 {v20_16:,.0f}円(約73万)")
print("OK: すべての数値が台本と一致")
