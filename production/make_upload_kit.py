SEISHIKI = ("生涯投資枠", "年間投資枠", "つみたて投資枠", "投資枠", "非課税枠")


def assert_no_bare_ryakugo(sid: str, *texts: str):
    for t in texts:
        for i, ch in enumerate(t):
            if ch != "枠":
                continue
            if any(t[max(0, i - len(k) + 1):i + 1] == k for k in SEISHIKI):
                continue
            around = t[max(0, i - 8):i + 8].replace("\n", " ")
            return (f"[NG] {sid}: 「枠」を裸で使っています: 「…{around}…」。"
                    f"「投資枠」と呼ぶこと(ループ71のユーザー指摘)")
    return None


def assert_tags_match(sid: str, script: str):
    """タグが**その動画の中身**を指しているか確かめる(ループ71)。

    IDを使い回してテーマを差し替えたとき、ここの対応表を直し忘れた。
    その結果 S012(4〜6月の残業と社会保険料)のタグが
    **「リボ払い」のまま**キットに出ていた(旧S012のテーマ)。
    表を手で持つ以上また起きるので、機械で照合する。

    判定: タグのうち少なくとも2つが script.md の本文に出てくること。
    共通タグ(お金の勉強など)は中身と関係ないので除く。
    """
    hit = [t for t in TAGS[sid] if t.replace(" ", "") in script.replace(" ", "")]
    if len(hit) < 2:
        return (f"[NG] {sid}: タグが台本の中身と合っていません。"
                f" タグ={TAGS[sid]} / 台本に出るのは={hit or 'なし'}")
    return None


def extract(script: str, header: str) -> str:
    m = re.search(rf"## {re.escape(header)}[^\n]*\n(.*?)(?=\n## |\Z)", script, re.S)
    if not m:
        return ""
    body = m.group(1).strip()
    lines = [l for l in body.splitlines() if not l.startswith("- 運用:") and not l.startswith("- 禁止:")]
    return "\n".join(lines).strip()


